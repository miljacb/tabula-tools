/**
 * @param {keyof typeof PATHS | string} name
 * @param {string} [className]
 */
export function icon(name, className = '') {
  const body = PATHS[/** @type {keyof typeof PATHS} */ (name)] || PATHS.skeleton;
  return `<svg class="outliner-icon ${className}" viewBox="0 0 24 24" width="14" height="14" fill="none" stroke="currentColor" stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

/** Icon name for an outliner node. @param {{ kind: string, type?: string }} node */
export function nodeIcon(node) {
  if (node.kind === 'group') {
    return { bones: 'bone', skins: 'skin', constraints: 'constraint', events: 'event', order: 'order' }[node.type || ''] || 'skeleton';
  }
  if (node.kind === 'attachment') return ['mesh', 'clipping', 'boundingbox', 'path', 'point'].includes(node.type || '') ? node.type : node.type === 'linkedmesh' ? 'constraint' : 'region';
  if (node.kind === 'constraint') return node.type || 'constraint';
  if (node.kind === 'asset') return 'skeleton';
  return node.kind;
}
